export const PROVINCES = Object.keys(REGIONS);

export function citiesOf(province?: string): string[] {
  if (!province || !REGIONS[province]) return [];
  return Object.keys(REGIONS[province]);
}

export function districtsOf(province?: string, city?: string): string[] {
  if (!province || !city || !REGIONS[province]?.[city]) return [];
  return REGIONS[province][city];
}

// 组合成一行显示地址
export function formatAddress(province?: string, city?: string, district?: string): string {
  const parts = [province, city, district].filter(Boolean);
  // 直辖市省市同名时去重
  const dedup = parts.filter((p, i) => i === 0 || p !== parts[i - 1]);
  return dedup.join(" · ");
}
